"use strict";
/**
 * Phase 19.8 in-Electron self-check (D-P16-0): orchestration/collaboration is measured by a real,
 * mock-first governed dispatch, not described by an author-shaped FINAL JSON file.
 *
 * The production emitter creates a caller-owned temporary store and loopback MCP server, decomposes
 * work, assigns by descriptor, publishes worker CANDIDATE artifacts, runs the real gates, and emits
 * the conductor synthesis/acceptance packet. It tears the server and store down before returning.
 * No provider CLI is launched and no live exchange is spent. The check also reads the shell's
 * launch-time dispatch state and the renderer pixel so the Python flow, Electron main and UI agree.
 */
const fs = require("node:fs");
const path = require("node:path");
const { receiptPath } = require("./receipt-path");
const { sourceIdentity } = require("./voice-conductor-selfcheck");

const FEED_SCHEMA = "conductor_dispatch_feed@1.0";
const RECEIPT_STAMP = new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "Z");
const RECEIPT_UNIT = String(process.env.SOW_SELFCHECK_UNIT || "run")
  .replace(/[^A-Za-z0-9._-]+/g, "-").slice(0, 40);
const RECEIPT_PATH = receiptPath(
  `PHASE19_8_ORCHESTRATION_COLLABORATION_SELFCHECK_${RECEIPT_UNIT}_${RECEIPT_STAMP}.json`);

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function evalRenderer(win, expression) {
  try { return await win.webContents.executeJavaScript(expression); }
  catch (error) { return { __error: `${error && error.name}: ${error && error.message}` }; }
}

function governedDispatchChecks(source) {
  const feed = (source && source.feed) || {};
  return {
    feed_sourced_from_production_emitter: Boolean(source && source.ok === true),
    feed_schema_is_pinned: feed.schema === FEED_SCHEMA,
    governed_dispatch_completed: feed.dispatched === true,
    assignments_are_by_descriptor: feed.by_descriptor === true,
    at_least_one_candidate_was_gate_accepted: Number(feed.accepted_count) > 0,
    acceptance_gate_passed: feed.acceptance_verdict === "PASS",
    synthesis_acceptance_packet_exists: typeof feed.acceptance_packet === "string"
      && feed.acceptance_packet.length > 0,
    operator_disposition_remains_pending: feed.operator_disposition === "pending",
    no_live_provider_leg_was_claimed: Boolean(feed.legs
      && feed.legs.conductor === "mock" && feed.legs.workers === "mock"),
    collaboration_resources_torn_down: feed.torn_down === true,
  };
}

async function run(ctx) {
  const { win, conductorState, conductorDispatchFeed, runGovernedDispatch, log } = ctx;
  const identity = typeof ctx.sourceIdentity === "function" ? ctx.sourceIdentity() : sourceIdentity();
  const receipt = {
    schema: "phase19_8_orchestration_collaboration_selfcheck@1.0",
    check: "orchestration-collaboration",
    unit: RECEIPT_UNIT,
    ok: false,
    started: new Date().toISOString(),
    finished: null,
    electron_main_pid: process.pid,
    electron: process.versions.electron || null,
    node: process.versions.node || null,
    platform: `${process.platform}-${process.arch}`,
    source: identity,
    live_exchanges: 0,
    measured_path: "Electron main -> production dispatch source -> Python governed live_flow "
      + "(temporary store + loopback MCP) -> CANDIDATE gates -> synthesis acceptance packet; "
      + "then Electron main state -> renderer dispatch line",
    check_owned_bindings: [
      "the run is mock-first by construction; its worker/conductor outputs are deterministic test "
        + "actors, explicitly reported as mock in feed.legs",
      "the temporary store and loopback MCP server are created by the production emitter for this run",
    ],
    not_measured_here: [
      "no live provider process, login, trust modal, permission prompt or model answer",
      "the historical FINAL_THREE_NODE and FINAL_TALK files are not regenerated by this check",
    ],
    checks: {},
    failed_checks: [],
    missing_checks: [],
    fresh_dispatch: null,
    launch_dispatch: null,
    main_state: null,
    renderer: null,
  };

  const expected = [
    "receipt_names_committed_source", "receipt_matches_clean_tracked_product_tree",
    ...Object.keys(governedDispatchChecks({})).map((name) => `fresh_${name}`),
    ...Object.keys(governedDispatchChecks({})).map((name) => `launch_${name}`),
    "main_reports_dispatch_sourced", "main_summary_matches_launch_feed",
    "renderer_draws_sourced_dispatch",
  ];

  try {
    receipt.checks.receipt_names_committed_source = typeof identity.commit === "string"
      && identity.commit.length >= 7;
    receipt.checks.receipt_matches_clean_tracked_product_tree =
      identity.tracked_product_tree_clean === true;

    if (typeof runGovernedDispatch !== "function") {
      throw new Error("runtime did not expose the production governed-dispatch source");
    }
    const fresh = await runGovernedDispatch({ liveWorkers: false, timeoutMs: 120000 });
    receipt.fresh_dispatch = fresh;
    for (const [name, value] of Object.entries(governedDispatchChecks(fresh))) {
      receipt.checks[`fresh_${name}`] = value;
    }

    const launch = typeof conductorDispatchFeed === "function" ? conductorDispatchFeed() : null;
    receipt.launch_dispatch = launch;
    for (const [name, value] of Object.entries(governedDispatchChecks(launch))) {
      receipt.checks[`launch_${name}`] = value;
    }

    const state = typeof conductorState === "function" ? conductorState() : null;
    receipt.main_state = state;
    receipt.checks.main_reports_dispatch_sourced = Boolean(state
      && state.dispatchRan === true && state.dispatchSourced === true);
    const launchFeed = (launch && launch.feed) || {};
    receipt.checks.main_summary_matches_launch_feed = Boolean(state && state.dispatch
      && state.dispatch.accepted === launchFeed.accepted_count
      && state.dispatch.owed === Boolean(launchFeed.live_workers_owed
        && launchFeed.live_workers_owed.owed === true));

    const paneId = state && state.paneId;
    let drawn = null;
    for (let attempt = 0; attempt < 50; attempt += 1) {
      drawn = paneId ? await evalRenderer(win,
        `window.__sovereignSelfCheck.conductorDispatchText(${JSON.stringify(paneId)})`) : null;
      if (drawn && drawn.isConductor && typeof drawn.text === "string"
        && drawn.text.includes("accepted") && drawn.text.includes("OWED")) break;
      await sleep(100);
    }
    receipt.renderer = drawn;
    receipt.checks.renderer_draws_sourced_dispatch = Boolean(drawn && drawn.isConductor
      && typeof drawn.text === "string" && drawn.text.includes("accepted")
      && drawn.text.includes("OWED"));
  } catch (error) {
    receipt.error = `${error && error.name}: ${error && error.message}`;
  }

  receipt.missing_checks = expected.filter((name) => !(name in receipt.checks));
  receipt.failed_checks = Object.entries(receipt.checks)
    .filter(([, value]) => value !== true).map(([name]) => name);
  receipt.ok = !receipt.error && receipt.missing_checks.length === 0
    && receipt.failed_checks.length === 0;
  receipt.finished = new Date().toISOString();

  try {
    fs.mkdirSync(path.dirname(RECEIPT_PATH), { recursive: true });
    fs.writeFileSync(RECEIPT_PATH, `${JSON.stringify(receipt, null, 2)}\n`);
  } catch (error) {
    receipt.ok = false;
    receipt.write_error = `${error && error.name}: ${error && error.message}`;
  }
  if (log) log(`[selfcheck:orchestration-collaboration] ok=${receipt.ok} `
    + `failed=${receipt.failed_checks.join(",") || "-"} -> ${RECEIPT_PATH}`);
  return receipt;
}

module.exports = { runOrchestrationCollaborationSelfCheck: run, governedDispatchChecks, RECEIPT_PATH };
